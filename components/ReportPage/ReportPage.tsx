import { useEffect, useState } from 'react';
import useDependencyTypes from '../../hooks/useDependencyTypes.ts';
import useLocation from '../../hooks/useLocation.ts';
import { PARAM_QUERY, PARAM_REGISTRY } from '../../lib/constants.ts';
import { createAbortable } from '../../lib/createAbortable.ts';
import { getGraphForQuery, type GraphState } from '../../lib/graph-util.ts';
import { parseReportPath } from '../../lib/report-util.ts';
import { searchGet } from '../../lib/url-util.ts';
import { ReportItems } from '../ReportPane/ReportPane.tsx';
import * as styles from './ReportPage.module.scss';

const isAnyModuleVisible = () => true;

function getGraphUrl(query: string[], registry: string | null) {
  const url = new URL('/', location.origin);
  url.searchParams.set(PARAM_QUERY, query.join(','));
  if (registry) {
    url.searchParams.set(PARAM_REGISTRY, registry);
  }

  return url.href;
}

/**
Standalone, nav-less version of the Report tab, served at `/report/{module}`
*/
export default function ReportPage() {
  const [location] = useLocation();
  const query = parseReportPath(location.pathname);
  const queryKey = query?.join(',') ?? '';
  const registry = searchGet(PARAM_REGISTRY, location);
  const dependencyTypes = useDependencyTypes();
  const [loaded, setLoaded] = useState<{
    queryKey: string;
    dependencyTypes: typeof dependencyTypes;
    graph: GraphState;
  }>();
  // Ignore the graph of a previous query until the new one is loaded
  const graph =
    loaded?.queryKey === queryKey && loaded.dependencyTypes === dependencyTypes
      ? loaded.graph
      : undefined;

  useEffect(() => {
    document.title = queryKey
      ? `npmgraph - Report for ${queryKey.replaceAll(',', ', ')}`
      : 'npmgraph - Report';
  }, [queryKey]);

  useEffect(() => {
    if (!queryKey) {
      return;
    }

    const { signal, abort } = createAbortable();
    void getGraphForQuery(
      queryKey.split(','),
      dependencyTypes,
      isAnyModuleVisible,
    ).then(newGraph => {
      if (!signal.aborted) {
        setLoaded({ queryKey, dependencyTypes, graph: newGraph });
      }
    });

    return abort;
  }, [queryKey, dependencyTypes]);

  const failures = graph ? [...graph.failedEntryModules] : [];

  return (
    <main className={styles.page}>
      <h1>
        Dependency report
        {query && (
          <>
            {' '}
            for <code>{queryKey.replaceAll(',', ', ')}</code>
          </>
        )}
      </h1>

      {query ? (
        <p className={styles.meta}>
          Generated by <a href="/">npmgraph</a> ·{' '}
          <a href={getGraphUrl(query, registry)}>View dependency graph</a>
        </p>
      ) : (
        <p>
          Specify a module, e.g. <a href="/report/send">/report/send</a>.
        </p>
      )}

      {query && !graph && <p className={styles.status}>Loading…</p>}

      {failures.map(([key, error]) => (
        <blockquote key={key} className={styles.error}>
          <p>
            Failed to load <code>{key}</code>: {error.message}
          </p>
        </blockquote>
      ))}

      {graph && graph.moduleInfos.size > 0 && <ReportItems graph={graph} />}
    </main>
  );
}
