export type OSIKeyword =
  | 'osi-approved'
  | 'discouraged'
  | 'non-reusable'
  | 'redundant'
  | 'popular'
  | 'obsolete'
  | 'copyleft'
  | 'special-purpose'
  | 'permissive'
  | 'miscellaneous'
  | 'retired';

export type License = {
  // From SPDX list
  id: string;
  name: string;
  isOsiApproved?: true;
  isDeprecatedLicenseId?: true;

  // From OSI list
  keywords?: OSIKeyword[];
};

export type Licenses = Record<string, License>;

let cached: Promise<Licenses> | undefined;

// separate chunk, fetched once on first use
export const loadLicenses = () =>
  (cached ??= import('./licenses_autogenerated.json').then(
    m => ((m as { default?: Licenses }).default ?? m) as Licenses,
  ));
