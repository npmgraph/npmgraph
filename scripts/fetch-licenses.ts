#!/usr/bin/env node

// This script fetches the OSI and SPDX license lists and combines the two in a
// single file that provides the most-interesting (to us) information from both.

import fs from 'node:fs/promises';
import type { OSIKeyword } from '../lib/licenses.ts';

type OSILicense = {
  id: string;
  name: string;
  spdx_id: string;
  version: string;
  submission_date: string;
  submission_url: string;
  submitter_name: string;
  approved: boolean;
  approval_date: string;
  license_steward_version: string;
  license_steward_url: string;
  board_minutes: string;
  stewards: string[];
  keywords: OSIKeyword[];
  _links: {
    self: { href: string };
    html: { href: string };
    collection: { href: string };
  };
};

type SPDXLicense = {
  reference: string;
  isDeprecatedLicenseId: boolean;
  detailsUrl: string;
  referenceNumber: number;
  name: string;
  licenseId: string;
  seeAlso: string[];
  isOsiApproved: boolean;
};

type GeneratedLicense = {
  id?: string;
  name?: string;
  isOsiApproved?: true;
  isDeprecatedLicenseId?: true;
  keywords?: OSIKeyword[];
};

const LICENSE_FILE = new URL(
  '../lib/licenses-autogenerated.json',
  import.meta.url,
);

const OSI_URL = 'https://opensource.org/api/license';
const SPDX_URL =
  'https://raw.githubusercontent.com/spdx/license-list-data/main/json/licenses.json';

const spdxResponse = await fetch(SPDX_URL);
const spdx: { licenses: SPDXLicense[] } = await spdxResponse.json();
const osiResponse = await fetch(OSI_URL);
const osiLicenses: OSILicense[] = await osiResponse.json();
const licenses = new Map<string, GeneratedLicense>();

function getLicense(id: string): GeneratedLicense {
  const lowerId = id.toLowerCase();
  const license = licenses.get(lowerId);
  if (license) {
    return license;
  }

  const newLicense: GeneratedLicense = {};
  licenses.set(lowerId, newLicense);
  return newLicense;
}

// Process SPDX licenses and populate the licenses map with initial data.
for (const {
  licenseId,
  name,
  isOsiApproved,
  isDeprecatedLicenseId,
} of spdx.licenses) {
  const l = getLicense(licenseId);
  l.id = licenseId;
  l.name = name;

  if (isOsiApproved) {
    l.isOsiApproved = true;
  }

  if (isDeprecatedLicenseId) {
    l.isDeprecatedLicenseId = true;
  }
}

// Process OSI licenses and update the licenses map with additional data.
for (const license of osiLicenses) {
  const spdxId = license.spdx_id;

  if (!spdxId) {
    console.warn(`Skipping OSI ${license.id} (no SPDX id)`);
    continue;
  }

  const { id, name } = license;
  const l = getLicense(id);

  l.id ??= id;
  l.name ??= name;

  if (!l.name) {
    console.warn(`No name for ${id}`, l);
  }

  if (license.keywords) {
    l.keywords = license.keywords;
  }

  if (license.approved) {
    l.isOsiApproved = true;
  }
}

const osiApprovedLicenses = [...licenses.values()]
  .filter(l => l.isOsiApproved)
  .toSorted((a, b) => (a.name ?? '').localeCompare(b.name ?? ''));

await fs.writeFile(
  LICENSE_FILE,
  `${JSON.stringify(osiApprovedLicenses, null, 2)}\n`,
);
